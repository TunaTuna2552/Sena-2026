"""Tipos de datos"""

#Tipo entero

numero= 5
print (numero + 5)

#Tipo float 

numero_decimal = 5.5
numero_decimal2 = 10.8

print(numero_decimal)
print(numero_decimal2)
print(numero_decimal + numero_decimal2)
print(type(numero_decimal))

#Tipo Complex - Números imagiarios
numero_complejo = 5j
print(numero_complejo)
print(type(numero_complejo))


#Tipo String - Tipo Cadena
nombre = "Edwin"
print(nombre)
print(type(nombre))

# Tipo Booleano
falso = False
print(falso)
print(type(falso))

# Tipo Lista
lista = ["valor1", "valor2", "valor3", 3, 2, 1, True, False [1, 2, 3]]
print(lista)

#Diccionario
print("Tipo de diccionario")
diccionario = {"nombre" : "Edwin",
               "apellido" : "Gonzales",
               "edad" : 86}
print(diccionario)
