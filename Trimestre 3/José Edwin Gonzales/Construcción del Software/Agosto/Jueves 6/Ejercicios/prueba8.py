#Tablas de la verdad compuertas
#Operador lógico AND
print(3==3 and  4==2)

#Operador lógico OR
print((3==1) or (4==4))

#Operador lógico NOT
print(not (3==2))

#Operador lógico IS
print("5" is "5")

#Operador lógico IS NOT
print("5" is not "5")

#Operador IN
lista =[1,2,3,4]
print (8 not in lista)

